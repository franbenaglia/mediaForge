"""Arma app/src/main/assets/third_party_notices.txt (T12.4).

Baja cada fuente de distribution/{gpl,notice}-sources.tsv y cada texto de distribution/notice-files.tsv,
verifica su SHA-256 y copia los archivos de licencia (LICENSE, COPYING, NOTICE, PATENTS…) que
traen en la raíz. Los textos repetidos se escriben una vez. Nada de lo bajado se ejecuta.
Uso: python3 -I scripts/build_notices.py (desde la raíz del repo; lo llama build-notices.sh).
"""

import hashlib
import io
import re
import subprocess
import sys
import tarfile
import zipfile
from pathlib import Path

ROOT = Path.cwd()
CACHE = ROOT / "build" / "notices" / "cache"
OUT = ROOT / "app" / "src" / "main" / "assets" / "third_party_notices.txt"
LICENSE_NAME = re.compile(
    r"^(licen[cs]e|copying|copyright|notice|patents|unlicense)([._-][a-z0-9.+-]*)?(\.txt|\.md)?$",
    re.IGNORECASE,
)
SKIP_SUFFIX = (".in", ".am", ".c", ".h", ".py", ".sh", ".html", ".xml")
MAX_FILE_BYTES = 200_000


def manifest(name):
    rows = []
    for line in (ROOT / "distribution" / name).read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        pkg, version, license_, url, sha = line.split("\t")
        rows.append((pkg, version, license_, url, sha))
    return rows


def fetch(url, sha):
    CACHE.mkdir(parents=True, exist_ok=True)
    target = CACHE / sha
    if not target.exists():
        part = target.with_suffix(".part")
        subprocess.run(
            ["curl", "-fsSL", "--retry", "3", "--connect-timeout", "30", "-o", str(part), url],
            check=True,
        )
        part.rename(target)
    actual = hashlib.sha256(target.read_bytes()).hexdigest()
    if actual != sha:
        target.unlink()
        sys.exit(f"SHA-256 distinto para {url}: esperado {sha}, bajado {actual}")
    return target.read_bytes()


def is_license(path):
    parts = path.split("/")
    name = parts[-1]
    if name.lower().endswith(SKIP_SUFFIX):
        return False
    # Una carpeta de licencias (pkg/LICENSES/MIT.txt): todo lo que tenga adentro.
    if len(parts) == 3 and parts[1].lower() in ("licenses", "license"):
        return True
    # Raíz del paquete (pkg/LICENSE, pkg/COPYING.LGPLv2.1…).
    return len(parts) == 2 and LICENSE_NAME.match(name) is not None


def _normalize(path):
    """`a/b/../c` → `a/c`, sin tocar el disco."""
    out = []
    for part in path.split("/"):
        if part in ("", "."):
            continue
        if part == "..":
            if out:
                out.pop()
        else:
            out.append(part)
    return "/".join(out)


def license_files(data):
    found = []
    if data[:2] == b"PK":
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            for info in z.infolist():
                if not info.is_dir() and is_license(info.filename) and info.file_size <= MAX_FILE_BYTES:
                    found.append((info.filename, z.read(info)))
    else:
        with tarfile.open(fileobj=io.BytesIO(data)) as t:
            members = {m.name.removeprefix("./"): m for m in t.getmembers()}
            for name, member in members.items():
                if not is_license(name):
                    continue
                # Algunos paquetes (GLib) tienen COPYING como enlace dentro del archivo: se sigue
                # (solo rutas relativas, como mucho 5 saltos).
                current = name
                for _ in range(5):
                    if not member.issym() or member.linkname.startswith("/"):
                        break
                    current = _normalize(f"{current.rsplit('/', 1)[0]}/{member.linkname}")
                    if current not in members:
                        break
                    member = members[current]
                if member.isfile() and member.size <= MAX_FILE_BYTES:
                    found.append((name, t.extractfile(member).read()))
    return sorted(found)


def main():
    sections = []
    for pkg, version, license_, url, sha in manifest("gpl-sources.tsv") + manifest("notice-sources.tsv"):
        if pkg.endswith("-patch"):
            continue
        files = license_files(fetch(url, sha))
        if not files:
            sys.exit(f"{pkg}: no se encontró ningún archivo de licencia en {url}")
        sections.append((pkg, version, license_, files))
    for name, version, license_, url, sha in manifest("notice-files.tsv"):
        sections.append((name, version, license_, [(url.rsplit("/", 1)[-1], fetch(url, sha))]))

    seen = {}
    lines = [
        "MediaForge: third-party notices",
        "",
        "Copyright notices and license texts of the components included in the app, taken from",
        "their original source. Generated by scripts/build-notices.sh; inventory in docs/LICENSES.md.",
        "MediaForge itself is free software under the GNU General Public License v3.0.",
        "",
    ]
    for name, version, license_, files in sections:
        title = f"{name} {version}" if version != "-" else name
        lines += ["=" * 78, f"{title}  ({license_})", "=" * 78, ""]
        for path, content in files:
            digest = hashlib.sha256(content).hexdigest()
            lines.append(f"--- {path}")
            if digest in seen:
                lines += [f"(Same text as {seen[digest]}.)", ""]
                continue
            seen[digest] = f"{title}, {path}"
            text = content.decode("utf-8", errors="replace").replace("\r\n", "\n").strip("\n")
            lines += [text, ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(sections)} components, {len(seen)} distinct texts, {OUT.stat().st_size // 1024} KB -> {OUT}")


if __name__ == "__main__":
    main()
